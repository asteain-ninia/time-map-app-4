// U24 受け入れ基準8 / 9 — press→move→release state machine, click vs drag,
// transient discard on every path (教訓5.8 / 5.7 / 5.2 / 5.22).

import { describe, expect, it } from 'vitest';

import {
  beginDrag,
  updateDrag,
  isNoOp,
  dragDelta,
  discardDrag,
  EDIT_TOOL,
  NO_SLIDE,
  type DragTarget,
} from './drag-session';
import { coord, fid, vid, rid } from './fixtures';

const vertexTarget: DragTarget = {
  tool: EDIT_TOOL.VertexMove,
  featureId: fid('F'),
  vertexId: vid('v0'),
  ringId: rid('r0'),
};

describe('beginDrag (教訓5.8 押下で開始状態)', () => {
  it('opens a session with preview === start (a press that has not moved)', () => {
    const s = beginDrag(vertexTarget, coord(1, 2));
    expect(s.start).toEqual({ lon: 1, lat: 2 });
    expect(s.preview).toEqual(s.start);
    expect(s.slide).toEqual(NO_SLIDE);
    expect(s.snap).toBeNull();
    expect(s.draggedVertexId).toBe(vid('v0')); // vertex-move carries the dragged id
  });

  it('feature-move has no single dragged vertex id', () => {
    const s = beginDrag({ tool: EDIT_TOOL.FeatureMove, featureId: fid('F') }, coord(0, 0));
    expect(s.draggedVertexId).toBeUndefined();
  });

  it('edge-add carries the RESERVED new vertex id as the dragged vertex (FR-89 / 受け入れ基準6 最終項)', () => {
    // The vertex generated by an edge-handle drag must be a snap / 共有化 candidate
    // just like a moved vertex; its identity is fixed at press as the reserved id so
    // the in-flight gesture can treat it as the dragged vertex.
    const s = beginDrag(
      {
        tool: EDIT_TOOL.EdgeAdd,
        featureId: fid('F'),
        startVertexId: vid('a'),
        endVertexId: vid('b'),
        ringId: rid('r0'),
        newVertexId: vid('new'),
      },
      coord(2, 2),
    );
    expect(s.draggedVertexId).toBe(vid('new'));
  });
});

describe('isNoOp — click vs drag (受け入れ基準9 / 教訓5.24)', () => {
  it('a press+release at the same position is a no-op (click)', () => {
    const s = beginDrag(vertexTarget, coord(1, 2));
    expect(isNoOp(s)).toBe(true);
  });

  it('a drag back to the start position is also a no-op (zero net move)', () => {
    let s = beginDrag(vertexTarget, coord(1, 2));
    s = updateDrag(s, { preview: coord(3, 4) });
    s = updateDrag(s, { preview: coord(1, 2) });
    expect(isNoOp(s)).toBe(true);
  });

  it('a real move is not a no-op', () => {
    let s = beginDrag(vertexTarget, coord(1, 2));
    s = updateDrag(s, { preview: coord(3, 4) });
    expect(isNoOp(s)).toBe(false);
    expect(dragDelta(s)).toEqual({ dLon: 2, dLat: 2 });
  });
});

describe('updateDrag — transient only (教訓5.22 破壊更新しない)', () => {
  it('returns a NEW session leaving the previous one unchanged (immutable)', () => {
    const s0 = beginDrag(vertexTarget, coord(0, 0));
    const s1 = updateDrag(s0, { preview: coord(5, 5) });
    expect(s0.preview).toEqual({ lon: 0, lat: 0 }); // unchanged
    expect(s1.preview).toEqual({ lon: 5, lat: 5 });
    expect(s1).not.toBe(s0);
  });

  it('keeps prior slide/snap when not provided, and clears snap when null is passed', () => {
    let s = beginDrag(vertexTarget, coord(0, 0));
    s = updateDrag(s, { preview: coord(1, 0), snap: { vertexId: vid('t'), screenDistance: 5 } });
    expect(s.snap).not.toBeNull();
    s = updateDrag(s, { preview: coord(2, 0) }); // snap omitted → preserved
    expect(s.snap).not.toBeNull();
    s = updateDrag(s, { preview: coord(3, 0), snap: null }); // snap dropped (lapsed)
    expect(s.snap).toBeNull();
  });
});

describe('discardDrag — single discard funnel for all termination paths (教訓5.2)', () => {
  it('returns the idle sentinel (null) so cancel / tool-change / mode-change share it', () => {
    expect(discardDrag()).toBeNull();
  });
});

// 受け入れ基準9 / 教訓5.7 — 連続シーケンス: the transient state of one gesture must
// NEVER bleed into the next. A drag session is a value object that the caller drops
// (discardDrag → null) on cancel/tool-change/mode-change and replaces wholesale on
// the next press (beginDrag). These tests fix that "開始→キャンセル→再操作" and
// "開始→確定→再操作" both start the second gesture from a pristine session — no
// carried-over preview / slide / snap — by driving press→move→discard→press and
// press→move→(release)→press at the domain level.
describe('continuous sequences — transient never carries to the next gesture (受け入れ基準9 / 教訓5.7)', () => {
  function buildSlide(): { boundaries: { featureId: string; edgeKey: string }[]; collided: boolean } {
    return { boundaries: [{ featureId: 'T', edgeKey: 'r:1' }], collided: true };
  }

  it('開始→移動→キャンセル(discard)→再開始: the second session is pristine', () => {
    // First gesture: move, accumulate slide + snap, then CANCEL.
    let s = beginDrag(vertexTarget, coord(1, 2));
    s = updateDrag(s, {
      preview: coord(8, 9),
      slide: buildSlide(),
      snap: { vertexId: vid('t'), screenDistance: 4 },
    });
    expect(s.preview).toEqual({ lon: 8, lat: 9 });
    expect(s.slide.collided).toBe(true);
    expect(s.snap).not.toBeNull();

    // Cancel: the single discard funnel returns idle. The caller drops the reference.
    const idle = discardDrag();
    expect(idle).toBeNull();

    // Re-operate: a fresh press opens a NEW session with no inherited transient.
    const s2 = beginDrag(vertexTarget, coord(3, 3));
    expect(s2.start).toEqual({ lon: 3, lat: 3 });
    expect(s2.preview).toEqual(s2.start); // not the cancelled gesture's (8,9)
    expect(s2.slide).toEqual(NO_SLIDE); // not the cancelled gesture's collided slide
    expect(s2.snap).toBeNull(); // not the cancelled gesture's snap
    expect(isNoOp(s2)).toBe(true); // a fresh press is a no-op until it moves
  });

  it('開始→移動→確定→再開始: the post-confirm session is pristine', () => {
    // First gesture: a real move that would confirm, then the caller discards.
    let s = beginDrag(vertexTarget, coord(1, 2));
    s = updateDrag(s, {
      preview: coord(5, 6),
      slide: buildSlide(),
      snap: { vertexId: vid('t'), screenDistance: 2 },
    });
    expect(isNoOp(s)).toBe(false);

    // Confirm path commits via edit-flow (covered in edit-flow.test.ts); the session
    // is then discarded through the SAME funnel as cancel (教訓5.2 全経路破棄).
    expect(discardDrag()).toBeNull();

    // Re-operate after a confirm: brand-new session, none of the prior transient.
    const s2 = beginDrag(vertexTarget, coord(7, 7));
    expect(s2.preview).toEqual({ lon: 7, lat: 7 });
    expect(s2.slide).toEqual(NO_SLIDE);
    expect(s2.snap).toBeNull();
  });

  it('a switched tool on the next press starts clean (tool-change discard then re-press)', () => {
    const s = beginDrag(vertexTarget, coord(1, 1));
    // Exercise an in-flight update (the transient that the tool-change discard must
    // wipe) without binding its result — the assertion below funnels through discard.
    updateDrag(s, { preview: coord(4, 4), snap: { vertexId: vid('t'), screenDistance: 1 } });
    expect(discardDrag()).toBeNull(); // tool-change funnels through discard

    // Next gesture uses a DIFFERENT tool: feature-move. No vertex id, no snap carried.
    const s2 = beginDrag({ tool: EDIT_TOOL.FeatureMove, featureId: fid('F') }, coord(0, 0));
    expect(s2.draggedVertexId).toBeUndefined();
    expect(s2.snap).toBeNull();
    expect(s2.slide).toEqual(NO_SLIDE);
  });
});
